import AppKit
import CryptoKit

/// One thing you copied.
struct ClipEntry: Codable, Equatable {
    enum Kind: String, Codable { case text, file, image }
    var id: String
    var kind: Kind
    /// The text itself, or the file's path, or where the image is saved.
    var value: String
    var app: String?
    var date: Date
}

/// Watches the clipboard and keeps a history on disk (~/Library/Application Support/Blink/clipboard.json).
/// Copies marked secret by password managers, and copies made in ignored apps, are never recorded.
final class ClipboardHistory {
    private(set) var entries: [ClipEntry] = []
    private let url: URL
    private let imagesDir: URL
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private let io = DispatchQueue(label: "blink.clipboard")
    var maxItems: Int
    var ignoreApps: Set<String>
    /// Pinned entries are kept when the history is trimmed.
    var keep: (String) -> Bool = { _ in false }

    /// Pasteboard types apps use to say "don't record this" (passwords, one-time codes, generated data).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    static let maxTextLength = 200_000

    init(url: URL, pasteboard: NSPasteboard = .general, maxItems: Int = 200, ignoreApps: [String] = []) {
        self.url = url
        self.pasteboard = pasteboard
        self.maxItems = maxItems
        self.ignoreApps = Set(ignoreApps)
        imagesDir = url.deletingLastPathComponent().appendingPathComponent("clipboard-images")
        lastChange = pasteboard.changeCount
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        if let d = try? Data(contentsOf: url), let list = try? JSONDecoder().decode([ClipEntry].self, from: d) { entries = list }
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let app = NSWorkspace.shared.frontmostApplication
        capture(bundleID: app?.bundleIdentifier, appName: app?.localizedName)
    }

    /// Records what's on the clipboard now, unless it's private or came from an ignored app.
    func capture(bundleID: String?, appName: String?) {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ClipboardHistory.privateTypes) else { return }
        if let bundleID, ignoreApps.contains(bundleID) { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let file = urls.first {
            add(.file, file.path, app: appName)
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= ClipboardHistory.maxTextLength {
            add(.text, text, app: appName)
        } else if let image = NSImage(pasteboard: pasteboard), let tiff = image.tiffRepresentation,
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            let id = ClipboardHistory.hash(png)
            let path = imagesDir.appendingPathComponent(id + ".png")
            try? png.write(to: path)
            add(.image, path.path, app: appName, id: id)
        }
    }

    static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).prefix(12).map { String(format: "%02x", $0) }.joined()
    }

    func add(_ kind: ClipEntry.Kind, _ value: String, app: String?, id: String? = nil, date: Date = Date()) {
        let id = id ?? ClipboardHistory.hash(Data((kind.rawValue + ":" + value).utf8))
        entries.removeAll { $0.id == id }  // copying it again moves it to the top
        entries.insert(ClipEntry(id: id, kind: kind, value: value, app: app, date: date), at: 0)
        trim()
        save()
    }

    func remove(_ id: String) {
        if let e = entries.first(where: { $0.id == id }), e.kind == .image { try? FileManager.default.removeItem(atPath: e.value) }
        entries.removeAll { $0.id == id }
        save()
    }

    func clear() {
        for e in entries where e.kind == .image && !keep("clip." + e.id) { try? FileManager.default.removeItem(atPath: e.value) }
        entries.removeAll { !keep("clip." + $0.id) }
        save()
    }

    private func trim() {
        var unpinned = 0
        entries = entries.filter { e in
            if keep("clip." + e.id) { return true }
            unpinned += 1
            if unpinned <= maxItems { return true }
            if e.kind == .image { try? FileManager.default.removeItem(atPath: e.value) }
            return false
        }
    }

    private func save() {
        let snapshot = entries, url = url
        io.async { try? JSONEncoder().encode(snapshot).write(to: url, options: .atomic) }
    }

    /// Puts an entry back on the clipboard without recording it as a new copy.
    func write(_ e: ClipEntry) {
        pasteboard.clearContents()
        switch e.kind {
        case .text: pasteboard.setString(e.value, forType: .string)
        case .file: pasteboard.writeObjects([URL(fileURLWithPath: e.value) as NSURL])
        case .image: if let img = NSImage(contentsOfFile: e.value) { pasteboard.writeObjects([img]) }
        }
        lastChange = pasteboard.changeCount
        add(e.kind, e.value, app: e.app, id: e.id)  // most recently used goes to the top
    }

    /// Puts it on the clipboard and pastes into the app you were in (⌘V needs Accessibility permission).
    func paste(_ e: ClipEntry) {
        write(e)
        guard AXIsProcessTrusted() else {
            // Ask once; until then the entry is just copied, ready for ⌘V.
            let prompt = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
            _ = AXIsProcessTrustedWithOptions([prompt: true] as CFDictionary)
            Log.write("clipboard: copied; pasting needs Accessibility permission")
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)  // V
            let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }
}

/// "v" + Tab (or the clipboard hotkey): everything you've copied, newest first.
final class ClipboardProvider: Provider {
    let name = "Clipboard"
    let keyword: String?
    let icon: Icon = .symbol("doc.on.clipboard")
    let history: ClipboardHistory
    private let now: () -> Date

    init(keyword: String, history: ClipboardHistory, now: @escaping () -> Date = Date.init) {
        self.keyword = keyword.lowercased()
        self.history = history
        self.now = now
    }

    private func age(_ d: Date) -> String {
        let s = now().timeIntervalSince(d)
        switch s {
        case ..<60: return "now"
        case ..<3600: return "\(Int(s / 60))m"
        case ..<86_400: return "\(Int(s / 3600))h"
        default: return "\(Int(s / 86_400))d"
        }
    }

    func item(_ e: ClipEntry) -> Item {
        let title: String
        let icon: Icon
        var details: [String] = [age(e.date)]
        if let app = e.app { details.append(app) }
        switch e.kind {
        case .text:
            let firstLine = e.value.split(whereSeparator: \.isNewline).first.map(String.init) ?? e.value
            title = String(firstLine.trimmingCharacters(in: .whitespaces).prefix(140))
            icon = .symbol("text.alignleft")
            let lines = e.value.split(whereSeparator: \.isNewline).count
            if lines > 1 { details.append("\(lines) lines") } else if e.value.count > 140 { details.append("\(e.value.count) characters") }
        case .file:
            title = (e.value as NSString).lastPathComponent
            icon = .file(e.value)
            details.append(e.value.replacingOccurrences(of: NSHomeDirectory(), with: "~"))
        case .image:
            title = "Image"
            icon = .thumbnail(e.value)
        }
        let history = self.history
        let paste = Action.run { history.paste(e) }
        return Item(id: "clip." + e.id, title: title, subtitle: details.joined(separator: " · "), icon: icon,
                    action: paste, altAction: .run { history.write(e) },
                    actions: [ItemAction("Paste", paste), ItemAction("Copy", .run { history.write(e) }),
                              ItemAction("Delete", .update { history.remove(e.id) })])
    }

    func favorites(_ ids: [String]) -> [Item] {
        history.entries.filter { ids.contains("clip." + $0.id) }.map(item)
    }

    func search(_ query: String) -> [Item] {
        let words = query.lowercased().split(separator: " ").map(String.init)
        return history.entries.filter { e in
            words.isEmpty || words.allSatisfy { e.value.lowercased().contains($0) || (e.app?.lowercased().contains($0) ?? false) }
        }.prefix(100).map(item)
    }
}
